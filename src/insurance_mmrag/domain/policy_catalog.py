def get_policy_card(doc_id: str) -> PolicyFeatureCard:
    """Return the normalized PolicyFeatureCard for a given doc_id."""
    if doc_id not in POLICY_CATALOG:
        raise KeyError(f"Unknown policy doc_id '{doc_id}'. Available: {list(POLICY_CATALOG)}")
    return POLICY_CATALOG[doc_id]


def list_policy_cards(include_accident: bool = True) -> list[PolicyFeatureCard]:
    """Return all PolicyFeatureCards in catalog order."""
    cards = list(POLICY_CATALOG.values())
    if not include_accident:
        return [c for c in cards if c.policy_category != "personal_accident"]
    return cards
